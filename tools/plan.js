// IrrigationGenie yard plan tool
// traced from AerialHouseView.png (352 x 471, north pointing right)
// rotates north-up, fits the 320 x 176 map area and prints:
//   - C++ default arrays (0..1000 normalized) for Storage.ino
//   - a clean SVG preview (AerialHouseView_clean.svg)
// usage: node tools/plan.js

const fs = require('fs');
const path = require('path');

const IMG_W = 352;
const MAP_W = 320, MAP_H = 176, MARGIN = 5;

// polygons in original image pixels
const plan = {
  property: [[37, 65], [283, 47], [305, 438], [42, 458], [18, 180]],
  house: [[78, 195], [165, 195], [165, 162], [205, 162], [210, 170], [210, 200], [237, 200], [237, 347],
          [178, 347], [178, 296], [125, 296], [122, 308], [95, 308], [78, 290]],
  drive: [[236, 200], [265, 200], [282, 440], [247, 447]],
  zones: [
    { n: 1, pts: [[22, 254], [68, 254], [68, 327], [178, 327], [178, 347], [243, 347], [245, 398], [39, 412]], label: [100, 367] },
    { n: 2, pts: [[25, 127], [287, 122], [290, 200], [248, 200], [248, 155], [155, 155], [155, 173], [62, 178],
                  [62, 228], [22, 228], [18, 180]], label: [120, 150] },
    { n: 3, pts: [[37, 65], [283, 47], [287, 122], [25, 127]], label: [153, 93] },
    { n: 4, pts: [[39, 412], [245, 398], [247, 447], [42, 458]], label: [114, 434] },
    { n: 5, pts: [[68, 254], [78, 254], [78, 290], [95, 308], [122, 308], [125, 296], [178, 296], [178, 327], [68, 327]], label: [152, 318] },
    { n: 6, pts: [[265, 200], [290, 200], [305, 438], [282, 440]], label: [288, 325] },
    { n: 7, pts: [[62, 178], [155, 173], [155, 155], [248, 155], [248, 200], [78, 200], [78, 254], [22, 254], [22, 228], [62, 228]], label: [122, 186] },
  ],
  houseLabel: [160, 254],
  driveLabel: [255, 330],
};

// rotate counter-clockwise so north (image +x) points up
const rot = ([x, y]) => [y, IMG_W - x];

const all = plan.property.map(rot);
const minX = Math.min(...all.map(p => p[0])), maxX = Math.max(...all.map(p => p[0]));
const minY = Math.min(...all.map(p => p[1])), maxY = Math.max(...all.map(p => p[1]));
const s = Math.min((MAP_W - 2 * MARGIN) / (maxX - minX), (MAP_H - 2 * MARGIN) / (maxY - minY));
const ox = (MAP_W - (maxX - minX) * s) / 2, oy = (MAP_H - (maxY - minY) * s) / 2;

// image px -> normalized 0..1000 of the map area
const norm = p => {
  const [x, y] = rot(p);
  return [Math.round(((x - minX) * s + ox) / MAP_W * 1000), Math.round(((y - minY) * s + oy) / MAP_H * 1000)];
};

const N = {
  property: plan.property.map(norm),
  house: plan.house.map(norm),
  drive: plan.drive.map(norm),
  zones: plan.zones.map(z => ({ n: z.n, pts: z.pts.map(norm), label: norm(z.label) })),
  houseLabel: norm(plan.houseLabel),
  driveLabel: norm(plan.driveLabel),
};

// ---- C++ output
const arr = (name, pts) =>
  `const int16_t ${name}[][2] = { ${pts.map(p => `{ ${p[0]}, ${p[1]} }`).join(', ')} };`;
let cpp = '// generated by tools/plan.js from AerialHouseView.png\n';
cpp += arr('PLAN_PROPERTY', N.property) + '\n';
cpp += arr('PLAN_HOUSE', N.house) + '\n';
cpp += arr('PLAN_DRIVE', N.drive) + '\n';
cpp += `const int16_t PLAN_HOUSE_LABEL[2] = { ${N.houseLabel.join(', ')} };\n`;
cpp += `const int16_t PLAN_DRIVE_LABEL[2] = { ${N.driveLabel.join(', ')} };\n`;
for (const z of N.zones) {
  cpp += arr(`PLAN_ZONE${z.n}`, z.pts) + `  // badge ${z.label.join(', ')}\n`;
}
console.log(cpp);

