// ---- raster preview of what the TFT draws (no text), written as PNG with built-in zlib
function rasterPreview(file, scale) {
  const zlib = require('zlib');
  const w = MAP_W * scale, h = MAP_H * scale;
  const buf = Buffer.alloc(w * h * 3);
  const hex = c => [parseInt(c.slice(1, 3), 16), parseInt(c.slice(3, 5), 16), parseInt(c.slice(5, 7), 16)];
  const set = (x, y, c) => { if (x >= 0 && y >= 0 && x < w && y < h) { const i = (y * w + x) * 3; buf[i] = c[0]; buf[i + 1] = c[1]; buf[i + 2] = c[2]; } };
  const P = pts => pts.map(p => [p[0] / 1000 * w, p[1] / 1000 * h]);
  const fill = (pts, c) => {   // same even-odd scanline as the firmware
    pts = P(pts);
    for (let y = 0; y < h; y++) {
      const xs = [];
      for (let i = 0, j = pts.length - 1; i < pts.length; j = i++) {
        const [x0, y0] = pts[j], [x1, y1] = pts[i];
        if ((y0 <= y && y1 > y) || (y1 <= y && y0 > y)) xs.push(x0 + (y - y0) * (x1 - x0) / (y1 - y0));
      }
      xs.sort((a, b) => a - b);
      for (let k = 0; k + 1 < xs.length; k += 2) for (let x = Math.ceil(xs[k]); x <= xs[k + 1]; x++) set(x, y, c);
    }
  };
  const line = (pts, c) => {
    pts = P(pts);
    for (let i = 0; i < pts.length; i++) {
      const [x0, y0] = pts[i], [x1, y1] = pts[(i + 1) % pts.length];
      const n = Math.ceil(Math.max(Math.abs(x1 - x0), Math.abs(y1 - y0)));
      for (let t = 0; t <= n; t++) { const x = Math.round(x0 + (x1 - x0) * t / n), y = Math.round(y0 + (y1 - y0) * t / n); set(x, y, c); set(x + 1, y, c); set(x, y + 1, c); }
    }
  };
  const blend = (a, b, t) => a.map((v, i) => Math.round(v * (1 - t) + b[i] * t));
  const bg = hex('#0b1426');
  for (let i = 0; i < w * h; i++) bg.forEach((v, k) => buf[i * 3 + k] = v);
  fill(N.property, hex('#13261d')); line(N.property, hex('#3b5b4a'));
  N.zones.forEach(z => fill(z.pts, blend(hex(colors[z.n - 1]), hex('#13261d'), 0.6)));
  N.zones.forEach(z => line(z.pts, hex(colors[z.n - 1])));
  fill(N.drive, hex('#2b3442')); line(N.drive, hex('#64748b'));
  fill(N.house, hex('#33415c')); line(N.house, hex('#9fb3c8'));
  N.zones.forEach(z => { const [cx, cy] = [z.label[0] / 1000 * w, z.label[1] / 1000 * h], r = 11 * scale;
    for (let y = -r; y <= r; y++) for (let x = -r; x <= r; x++) if (x * x + y * y <= r * r) set(Math.round(cx + x), Math.round(cy + y), x * x + y * y > (r - 2 * scale) ** 2 ? [255, 255, 255] : hex(colors[z.n - 1])); });
  // PNG encode
  const raw = Buffer.alloc((w * 3 + 1) * h);
  for (let y = 0; y < h; y++) buf.copy(raw, y * (w * 3 + 1) + 1, y * w * 3, (y + 1) * w * 3);
  const crcT = []; for (let n = 0; n < 256; n++) { let c = n; for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1; crcT[n] = c >>> 0; }
  const crc = b => { let c = 0xffffffff; for (const v of b) c = crcT[(c ^ v) & 255] ^ (c >>> 8); return (c ^ 0xffffffff) >>> 0; };
  const chunk = (t, d) => { const l = Buffer.alloc(4); l.writeUInt32BE(d.length); const td = Buffer.concat([Buffer.from(t), d]); const c = Buffer.alloc(4); c.writeUInt32BE(crc(td)); return Buffer.concat([l, td, c]); };
  const ihdr = Buffer.alloc(13); ihdr.writeUInt32BE(w, 0); ihdr.writeUInt32BE(h, 4); ihdr[8] = 8; ihdr[9] = 2;
  fs.writeFileSync(file, Buffer.concat([Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]), chunk('IHDR', ihdr), chunk('IDAT', zlib.deflateSync(raw)), chunk('IEND', Buffer.alloc(0))]));
}
rasterPreview(path.join(__dirname, 'preview.png'), 2);

